function buildAgentsMd(fieldName, rolesTable) {
  return [
    '# ' + (fieldName || 'This field'),
    '',
    'You are this restaurant\'s assistant. One assistant, many roles.',
    '',
    '## Your roles',
    '',
    rolesTable || DEFAULT_ROLES_TABLE,
    '',
    buildFrameworkBlock(),
    '',
  ].join('\n');
}

// ── CLAUDE.md, retired (2026-10-15) ───────────────────────────────────────
// From 2026-09-25 to 2026-10-15 keeper-sync wrote a CLAUDE.md glue file that
// imported AGENTS.md. The marker is what still recognises that generated file,
// so the next run can delete it without touching a CLAUDE.md a person wrote.
var GLUE_MARKER = '<!-- bnb:claude-glue — generated by keeper-sync from .bnb/canon/claude-md-core.cjs; the framework block lives in AGENTS.md -->';

// Has this file's content already moved to AGENTS.md? True for the generated
// glue, and also for a field that wrote its own `@AGENTS.md` import by hand —
// either way CLAUDE.md must not be treated as the source again.
function isClaudeGlue(content) {
  var src = String(content || '');
  return src.indexOf(GLUE_MARKER) !== -1 || /^@AGENTS\.md[ \t]*$/m.test(src);
}

// What to do with an existing CLAUDE.md once AGENTS.md holds the entry point.
//   'delete'  — the generated glue (it carries the marker): ours to remove;
//   'keep'    — anything a person wrote, an `@AGENTS.md` import included.
//               Never deleted here: a destructive act fails closed. A kept
//               file that is NOT an import shadows AGENTS.md, so the caller
//               reports it ('shadowing').
function claudeVerdict(content) {
  var src = String(content || '');
  if (src.trim() === '') return 'absent';
  if (src.indexOf(GLUE_MARKER) !== -1) return 'delete';
  return isClaudeGlue(src) ? 'keep' : 'shadowing';
}

/**
 * Move a field's entry point to AGENTS.md. Idempotent, and lossless by
 * construction: the WHOLE of CLAUDE.md moves, not the block alone, so the
 * field's own title, intro, roles table and rules travel with it.
 *
 *   { agents, deleteClaude, claude, action }
 *   agents       — AGENTS.md's new content;
 *   deleteClaude — true when CLAUDE.md is ours to remove (its content moved,
 *                  or it is the generated glue);
 *   claude       — 'absent' | 'deleted' | 'keep' | 'shadowing' (for the log);
 *   action       — 'migrated' (CLAUDE.md's content became AGENTS.md) |
 *                  'created' (neither file had content) | the splice's own
 *                  verdict ('updated' | 'unchanged' | 'adopted' | 'appended').
 *
 * `claudeContent` / `agentsContent` are the files' current contents, or null
 * when absent. The caller writes AGENTS.md and removes CLAUDE.md.
 */
function migrateToAgents(claudeContent, agentsContent, fieldName, rolesTable) {
  var claude = String(claudeContent || '');
  var agents = String(agentsContent || '');

  if (agents.trim() !== '') {
    var r = spliceFrameworkBlock(agents);
    var v = claudeVerdict(claude);
    return { agents: r.content, deleteClaude: v === 'delete', claude: v === 'delete' ? 'deleted' : v, action: r.action };
  }
  if (claude.trim() !== '' && !isClaudeGlue(claude)) {
    // The one-time move. Re-splice on the way across so the block is current
    // in its new home, and so a marker-less CLAUDE.md is adopted exactly as it
    // would have been in place — the adopt path survives the move.
    return { agents: spliceFrameworkBlock(claude).content, deleteClaude: true, claude: 'deleted', action: 'migrated' };
  }
  // Neither file has content worth keeping (a new repo, or a CLAUDE.md that is
  // nothing but glue pointing at an AGENTS.md that went missing).
  var vc = claudeVerdict(claude);
  return { agents: buildAgentsMd(fieldName, rolesTable), deleteClaude: vc === 'delete', claude: vc === 'delete' ? 'deleted' : vc, action: 'created' };
}

// ── The roster leaves router.md (2026-10-15) ──────────────────────────────
// A field's roster used to be its workers/router.md dispatch table: a row per
// role, a markdown link to the role file, a Triggers cell. That file retires,
// so its rows fold into the AGENTS.md roles table first — slug and triggers,
// one row per role the table does not already name. Only a role whose file
// still exists is carried (`roleExists(relPath)`), so a table row never points
// at nothing. Idempotent: a second run finds every slug already present.

var ROLES_SECTION = sectionRegex('Your roles');

// Pure: the slugs a roles table names in its first column — `backend-developer`,
// `` `keeper` ``, `[guide](...)` all read as the bare slug.
function tableSlugs(section) {
  var out = {};
  String(section || '').split('\n').forEach(function (line) {
    if (!/^\s*\|/.test(line)) return;
    var first = line.split('|')[1];
    if (!first) return;
    var slug = first.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[`*]/g, '').trim().toLowerCase();
    if (/^[a-z0-9][\w-]*$/.test(slug)) out[slug] = true;
  });
  return out;
}

// Pure: the roster router.md declares — [{ slug, rel, triggers }] in table
// order. A row counts when it links a `.md` file inside `workers/`; the slug is
// the file's basename and the triggers are the row's last cell.
function parseRouterRoles(routerText) {
  var roles = [];
  var seen = {};
  String(routerText || '').split('\n').forEach(function (line) {
    if (!/^\s*\|/.test(line)) return;
    var m = /\]\(([^)\s]+\.md)\)/.exec(line);
    if (!m) return;
    var rel = m[1];
    if (/:\/\//.test(rel) || rel.charAt(0) === '/' || rel.indexOf('..') !== -1) return;
    var slug = rel.replace(/^.*\//, '').replace(/\.md$/, '');
    if (!slug || seen[slug]) return;
    var cells = line.replace(/^\s*\|/, '').replace(/\|\s*$/, '').split('|');
    var triggers = (cells[cells.length - 1] || '').trim();
    seen[slug] = true;
    roles.push({ slug: slug, rel: rel, triggers: triggers });
  });
  return roles;
}

/**
 * Fold router.md's roster into AGENTS.md's roles table.
 *   { content, added }  added: the slugs given a new row.
 * No `## Your roles` section, or no table in it → unchanged (nothing to append
 * to; the field's AGENTS.md is its own).
 */
function foldRouterRoles(agentsContent, routerText, roleExists) {
  var src = String(agentsContent || '');
  var exists = typeof roleExists === 'function' ? roleExists : function () { return true; };
  var m = src.match(ROLES_SECTION);
  if (!m) return { content: src, added: [] };
  var lines = m[0].split('\n');
  var lastRow = -1;
  for (var i = 0; i < lines.length; i++) if (/^\s*\|/.test(lines[i])) lastRow = i;
  if (lastRow === -1) return { content: src, added: [] };
  var present = tableSlugs(m[0]);
  var rows = [];
  var added = [];
  parseRouterRoles(routerText).forEach(function (r) {
    if (present[r.slug] || !exists(r.rel)) return;
    present[r.slug] = true;
    added.push(r.slug);
    rows.push('| ' + r.slug + ' | ' + (r.triggers || '').replace(/\|/g, '/') + ' |');
  });
  if (rows.length === 0) return { content: src, added: [] };
  var section = lines.slice(0, lastRow + 1).concat(rows, lines.slice(lastRow + 1)).join('\n');
  return { content: src.slice(0, m.index) + section + src.slice(m.index + m[0].length), added: added };
}

